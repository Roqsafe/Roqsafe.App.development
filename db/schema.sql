CREATE TABLE IF NOT EXISTS svi_content (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page varchar(80) NOT NULL DEFAULT 'main',
  "key" varchar(120) NOT NULL,
  "value" text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (page, "key")
);

CREATE TABLE IF NOT EXISTS svi_blocked_ips (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip varchar(45) NOT NULL UNIQUE,
  block_type text NOT NULL DEFAULT 'soft' CHECK (block_type IN ('soft', 'permanent')),
  reason text,
  deblock_req boolean NOT NULL DEFAULT false,
  deblocked boolean NOT NULL DEFAULT false,
  blocked_website varchar(255),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS blocked_ips (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip_address varchar(45) NOT NULL UNIQUE,
  reason varchar(255) NOT NULL DEFAULT '',
  active boolean NOT NULL DEFAULT true,
  blocked_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS svi_admins (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(60) NOT NULL UNIQUE,
  password_hash varchar(255) NOT NULL,
  email varchar(120),
  last_login timestamptz,
  login_attempts integer NOT NULL DEFAULT 0,
  locked_until timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS svi_login_log (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(60) NOT NULL,
  ip varchar(45) NOT NULL,
  success boolean NOT NULL DEFAULT false,
  user_agent text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS svi_settings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  setting_key varchar(80) NOT NULL UNIQUE,
  "value" text NOT NULL,
  label varchar(120) NOT NULL DEFAULT '',
  description varchar(255) NOT NULL DEFAULT '',
  type text NOT NULL DEFAULT 'text' CHECK (type IN ('boolean', 'integer', 'text', 'email', 'textarea')),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS svi_check_log (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip varchar(45) NOT NULL,
  target_ip varchar(45) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_svi_check_log_ip_created ON svi_check_log (ip, created_at);

